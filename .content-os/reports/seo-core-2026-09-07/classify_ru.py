#!/usr/bin/env python3
"""Три фильтра брифа, адаптированные под рынок внедрения ИИ и lead ops.
1. Потребительский / развлекательный ИИ вместо делового
2. Омонимы и ложное гео (воронка, свинец, лид как металл, иноагент)
3. Тема: фраза должна быть про внедрение, автоматизацию, покупку услуги или систему,
   а не просто содержать слово ИИ."""
import json, re, collections

d = json.load(open('ru-core.json', encoding='utf-8'))

REJ = [
 ('работа_учеба',   re.compile(r'вакансии|ваканси|работа |работу|зарплат|курс|обучени|учить|научить|профессия|'
                               r'реферат|диплом|презентац|доклад|стажировк|резюме|собеседован|тест |егэ|'
                               r'университет|колледж|специальност|professiya')),
 ('потребит_ии',    re.compile(r'нейросет[ьи]? (для )?(рисован|фото|видео|текст|музык|картин|изображен|аниме|'
                               r'песен|голос|озвуч|перевод|стих|мем|аватар|обои|логотип)|'
                               r'midjourney|kandinsky|dall|шедеврум|deepseek|qwen|gemini|copilot|grok|'
                               r'нейросеть онлайн|нейросеть бесплатно|все нейросети|список нейросетей|'
                               r'лучшие нейросети|нейросеть раздевает|нейро(сеть)? рисует|дипфейк|deepfake|'
                               r'chat ?gpt (скачать|бесплатн|онлайн|на русском|вход|регистрац)')),
 ('справка_общая',  re.compile(r'^(что такое|что значит|кто такой|как работает|определение|это )|'
                               r'(что это|это что|значение|своими словами|простыми словами|расшифровка|'
                               r'на английском|перевод)$|википеди|вики$')),
 ('омоним',         re.compile(r'иноагент|воронк[аиуе] (для|бюхнер|масл|бензин|дожд|торнадо)|'
                               r'^воронк|свинц|свинец|грузил|припой|карандаш|поводок|'
                               r'лид[еэ]р|лидер|дегустац|аудит (квартир|жкх|энергет|пожарн|кадров)')),
 ('не_услуга',      re.compile(r'скачать|бесплатн|торрент|взлом|крякн|apk|мод |промокод|подписка на|'
                               r'акци[ия]|дивиденд|котировк|биржа|инвестиц|купить акции')),
]
# Тематический якорь: услуга внедрения / автоматизации / система обработки
ANCHOR_B = re.compile(r'внедрен|интеграц|автоматизац|разработ|настрой|подключ|создан|построен|'
                      r'консалт|консультац|агентств|подряд|под ключ|аутсорс|услуг|заказать|'
                      r'стоимость|цена|сколько стоит|кейс|аудит')
TOPIC_B  = re.compile(r'\bии\b|искусственн(ый|ого|ым) интеллект|нейросет|\bai\b|gpt|chatgpt|llm|'
                      r'агент|ассистент|бот|чат.?бот|голосов(ой|ого) робот|n8n|make\.com|zapier')
TOPIC_A  = re.compile(r'crm|amocrm|amo crm|битрикс|заявк|лид[аыоу]?\b|лидогенерац|воронк[аиуе] продаж|'
                      r'отдел продаж|сквозн(ая|ой) аналитик|скоринг|квалификац|распределен|'
                      r'телефони|обработк[аи] (заявок|обращен|лидов)')
BIZ      = re.compile(r'бизнес|компан|предприят|организац|отдел|b2b|корпорат|продаж|клиент|заявк|лид')

kept = {}; rejected = {}
for t, meta in d.items():
    v = meta['v']
    why = None
    for name, rx in REJ:
        if rx.search(t): why = name; break
    if why is None:
        hasB = bool(TOPIC_B.search(t)); hasA = bool(TOPIC_A.search(t))
        if not (hasB or hasA):
            why = 'вне_темы'
        elif hasB and not (ANCHOR_B.search(t) or BIZ.search(t)):
            why = 'ии_без_делового_якоря'
    if why:
        rejected[t] = {'v': v, 'why': why}
    else:
        core = 'B_внедрение_ии' if TOPIC_B.search(t) else 'A_lead_ops'
        kept[t] = {'v': v, 'core': core, 'seed': meta['seed'], 'src': meta['src']}

print(f'принято {len(kept):5d} фраз, {sum(x["v"] for x in kept.values()):>10,d} показов/мес')
print(f'отсеяно {len(rejected):5d} фраз, {sum(x["v"] for x in rejected.values()):>10,d} показов/мес')
print()
rc = collections.Counter(); rv = collections.Counter()
for t, m in rejected.items(): rc[m['why']] += 1; rv[m['why']] += m['v']
print(f'{"причина отсева":26s} {"фраз":>6s} {"показов":>12s}')
for w, c in rc.most_common(): print(f'{w:26s} {c:6d} {rv[w]:12,d}')
print()
cc = collections.Counter(); cv = collections.Counter()
for t, m in kept.items(): cc[m['core']] += 1; cv[m['core']] += m['v']
print(f'{"ядро":18s} {"фраз":>6s} {"показов":>12s}')
for c, n in cc.most_common(): print(f'{c:18s} {n:6d} {cv[c]:12,d}')

json.dump({'kept': kept, 'rejected': rejected}, open('ru-core-classified.json','w',encoding='utf-8'),
          ensure_ascii=False, indent=0)
print('\n--- ТОП-40 принятых ---')
for t, m in sorted(kept.items(), key=lambda x: -x[1]['v'])[:40]:
    print(f'{m["v"]:7,d}  {m["core"][:1]}  {t}')
