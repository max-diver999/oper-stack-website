#!/usr/bin/env python3
"""Три фильтра, ужесточённая версия. Правило: фраза наша, только если в ней есть
и ТЕМА (ИИ/автоматизация или lead ops), и КОММЕРЧЕСКИЙ ЯКОРЬ (заказ услуги/системы),
и она не попала ни в один стоп-класс."""
import json, re, collections
d = json.load(open('ru-core.json', encoding='utf-8'))

REJ = [
 ('навигация',     re.compile(r'\b(войти|вход|логин|личный кабинет|регистрац|скачать|официальный сайт|'
                              r'приложение|apk|как пишется|как писать|ударение)\b')),
 ('чужой_бренд',   re.compile(r'полезный звонок|мухич|say agency|лидс медиа|эра перемен|детективн|'
                              r'кадровое агентство|рекламное агентство|туристическ|недвижимост|'
                              r'информационное агентство|новостное агентство|агентство свои|'
                              r'агентство зачем звонят|коллекторск|ритуальн|брачное')),
 ('работа_учеба',  re.compile(r'ваканси|работа |работу|зарплат|курс|обучени|учить|научить|профессия|'
                              r'реферат|диплом|презентац|доклад|стажировк|резюме|собеседован|егэ|'
                              r'университет|колледж|специальност')),
 ('потребит_ии',   re.compile(r'создать \w+ с помощью нейросет|создать \w+ нейросет|как создать (нейросеть|нейронную)|нейросет[ьи]? (для )?(создан|рисован|фото|видео|текст|музык|картин|изображен|'
                              r'аниме|песен|голос|озвуч|перевод|стих|мем|аватар|обои|логотип|презентац)|'
                              r'midjourney|kandinsky|dall|шедеврум|deepseek|qwen|gemini|copilot|grok|'
                              r'нейросеть онлайн|нейросеть бесплатно|все нейросети|список нейросет|'
                              r'лучшие нейросет|дипфейк|нейро(сеть)? рисует')),
 ('справка',       re.compile(r'^(что такое|что значит|кто такой|как работает|определение|зачем|почему)\b|'
                              r'\b(это|что это|это что|значение|своими словами|простыми словами|'
                              r'расшифровка|на английском|пример(ы)?|плюсы и минусы|история)$|'
                              r'^(crm|битрикс|битрикс ?24|amocrm|нейросеть|искусственный интеллект|ии)$')),
 ('омоним',        re.compile(r'иноагент|^воронк|воронк[аиуе] (для|бюхнер|масл|бензин|дожд)|свинц|свинец|'
                              r'грузил|припой|лид[еэ]р|дегустац|аудит (квартир|жкх|энергет|пожарн|кадров)|'
                              r'постановка на учет|скоринг бюро|бюро кредитных')),
 ('мусор_базы',    re.compile(r'ошибка настройки|тестовой инфраструктуры|разработка и управление программным обеспечением|^сколько стоит робот$')),
 ('не_услуга',     re.compile(r'бесплатн|торрент|взлом|крякн|мод |промокод|дивиденд|котировк|биржа|'
                              r'купить акции|отзывы сотрудников')),
]
TOPIC_B = re.compile(r'\bии\b|искусственн\w* интеллект\w*|нейросет\w*|\bai\b|\bgpt\b|chat ?gpt|llm|'
                     r'\bагент\w*|ассистент\w*|чат.?бот\w*|\bбот\w*|голосов\w+ робот|n8n|make\.com|zapier|'
                     r'робот\w* (для|в) ')
TOPIC_A = re.compile(r'\bcrm\b|amo ?crm|битрикс|заявк\w*|\bлид\w*|лидогенерац\w*|воронк\w* продаж|'
                     r'отдел\w* продаж|сквозн\w* аналитик\w*|скоринг|квалификац\w*|распределен\w*|'
                     r'телефони\w*|обработк\w* (заявок|обращен|лидов)|автоматизац\w* продаж')
# коммерческий якорь = заказ услуги или построение системы
ANCHOR = re.compile(r'внедрен\w*|интеграц\w*|автоматизац\w*|разработк\w*|разработать|настройк\w*|настроить|'
                    r'подключ\w*|создани\w*|создать|построен\w*|внедрить|консалтинг|консультац\w*|'
                    r'под ключ|аутсорс\w*|услуг\w*|заказать|стоимость|цена|сколько стоит|'
                    r'для бизнеса|для компани|для предприят|для отдела продаж|для b2b|в бизнесе|'
                    r'аудит бизнес|кейс\w*|подрядчик|исполнител')

kept, rejected = {}, {}
for t, meta in d.items():
    v = meta['v']; why = None
    for name, rx in REJ:
        if rx.search(t): why = name; break
    if why is None:
        hasB, hasA = bool(TOPIC_B.search(t)), bool(TOPIC_A.search(t))
        if not (hasB or hasA):       why = 'вне_темы'
        elif not ANCHOR.search(t):   why = 'тема_без_коммерч_якоря'
    (rejected if why else kept)[t] = ({'v': v, 'why': why} if why else
        {'v': v, 'core': 'B_внедрение_ии' if TOPIC_B.search(t) else 'A_lead_ops',
         'seed': meta['seed'], 'src': meta['src']})

kv = sum(x['v'] for x in kept.values()); rv_ = sum(x['v'] for x in rejected.values())
print(f'ПРИНЯТО {len(kept):5d} фраз  {kv:>9,d} показов/мес')
print(f'ОТСЕЯНО {len(rejected):5d} фраз  {rv_:>9,d} показов/мес')
print(f'доля делового спроса в сыром сборе: {kv/(kv+rv_)*100:.1f} %\n')
rc, rvv = collections.Counter(), collections.Counter()
for t, m in rejected.items(): rc[m['why']] += 1; rvv[m['why']] += m['v']
print(f'{"причина отсева":26s} {"фраз":>6s} {"показов":>12s}')
for w, c in rc.most_common(): print(f'{w:26s} {c:6d} {rvv[w]:12,d}')
cc, cv = collections.Counter(), collections.Counter()
for t, m in kept.items(): cc[m['core']] += 1; cv[m['core']] += m['v']
print(f'\n{"ядро":18s} {"фраз":>6s} {"показов":>12s}')
for c, n in cc.most_common(): print(f'{c:18s} {n:6d} {cv[c]:12,d}')
json.dump({'kept': kept, 'rejected': rejected}, open('ru-core-classified.json','w',encoding='utf-8'),
          ensure_ascii=False, indent=0)
print('\n--- ТОП-45 принятых ---')
for t, m in sorted(kept.items(), key=lambda x: -x[1]['v'])[:45]:
    print(f'{m["v"]:7,d}  {m["core"][:1]}  {t}')
