/**
 * Оплата картой на страницах продуктов.
 *
 * Продавец здесь Whop: Paddle отказал по категории, потому что берёт ответственность за сделку
 * на себя и услуги не обслуживает. Whop это обычная площадка, она не решает, чем нам торговать.
 * Ссылка ведёт на их страницу оплаты, куда покупатель приходит уже знающим, что берёт.
 *
 * Включение по-прежнему идёт от переменных окружения: нет ссылки, значит нет кнопки, и страница
 * показывает форму заказа. Так кнопка не может появиться раньше, чем за ней есть рабочая оплата.
 *
 * Переменные (Vercel, окружение production):
 *   PUBLIC_WHOP_CHECKOUT_SITE_KIT  ссылка на оплату Site Kit
 *   PUBLIC_WHOP_CHECKOUT_AUDIT     ссылка на оплату аудита
 *
 * Кнопка есть только там, где купить можно сразу, ничего не согласовывая: комплект скачивается,
 * аудит делается по одному адресу сайта. У Fix и Foundation кнопки нет и не будет: их страницы
 * обещают, что список работ согласуется письменно до оплаты, а кнопка позволила бы заплатить
 * раньше согласования. Ссылку на оплату им отправляют после того, как клиент утвердил список.
 */

/** Ключи читаются по одному: Vite подставляет только те, что написаны в коде буквально. */
const LINK_BY_SLUG: Record<string, string> = {
  'site-kit': String(import.meta.env.PUBLIC_WHOP_CHECKOUT_SITE_KIT || '').trim(),
  'seo-audit': String(import.meta.env.PUBLIC_WHOP_CHECKOUT_AUDIT || '').trim(),
};

/** Принимаем только адрес самого Whop: опечатка в переменной не должна увести покупателя никуда. */
const isCheckoutLink = (x: string) => /^https:\/\/whop\.com\/[a-z0-9-]+\/[a-z0-9-]+\/?$/i.test(x);

/** Ссылка на оплату для товара, если она задана и выглядит как настоящая. */
export function checkoutLink(slug: string): string | null {
  const url = LINK_BY_SLUG[slug] || '';
  return isCheckoutLink(url) ? url : null;
}

/** Надпись на кнопке. Цена берётся из карточки товара, чтобы не разошлась с тем, что на странице. */
export function buyLabel(price: string): string {
  return `Buy for ${price}`;
}
